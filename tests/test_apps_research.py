def patch(client, ch):
    return client.patch("/api/settings", json={"changes": ch})


def test_giving_an_app_more_access_waits_for_a_yes(client, settings):
    r = patch(client, {"app_permissions": {"chrome.exe": "full"}})
    assert r.status_code == 202 and r.json()["pending"] == ["app_permissions"]
    assert settings.get("app_permissions").get("chrome.exe") is None
    assert patch(client, {"app_permissions": {"spotify.exe": "open"}}).status_code == 200      # lowering is instant
    assert settings.get("app_permissions")["spotify.exe"] == "open"
    r = client.post("/api/text", json={"text": "yes"})
    assert r.status_code == 200
    assert settings.get("app_permissions")["chrome.exe"] == "full"


