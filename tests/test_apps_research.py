# ---------- the gate follows your choices ----------
def act(gate, proc, kind="click"):
    key = "minimize" if kind == "window" else ""
    return gate.authorize(Action(kind, 1, proc, "Some window", "Play", key=key, ctype="Button"), dry=True)


def test_gate_off_open_full(settings):
    gate = Gate(settings, None)
    settings.update({"app_permissions": {"chrome.exe": "open", "blender.exe": "full", "notepad.exe": "off"}})
    assert act(gate, "blender.exe").verdict == "allow"
    assert act(gate, "spotify.exe").verdict == "allow"                     # one of the defaults
    d = act(gate, "chrome.exe")
    assert d.verdict == "deny" and "Apps list" in d.say
    assert act(gate, "chrome.exe", "window").verdict == "allow"           # open = may move its window
    assert act(gate, "notepad.exe", "window").verdict == "deny"
    d = act(gate, "roblox.exe")
    assert d.verdict == "deny" and "permission" in d.say                   # nothing chosen yet: no clicking or typing
    settings.update({"app_access": "any"})
    assert act(gate, "roblox.exe").verdict == "allow"
    assert act(gate, "cmd.exe").verdict == "deny"                          # the hard blocks never move


